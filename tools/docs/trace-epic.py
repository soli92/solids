#!/usr/bin/env python3
"""trace-epic.py — traccia di un'epica dal kanban e da git (EP-080 US-352).

Ricostruisce la catena decisione → epica → storie → task (date, chiusura con evidenza) →
commit → PR → voce di wiki/log.md, leggendo solo file e storia git. Non scrive nel kanban.
La pagina e' generata, non scritta a mano: rigenerarla e' l'unico modo di aggiornarla.

  python3 tools/docs/trace-epic.py EP-079                         # markdown su stdout
  python3 tools/docs/trace-epic.py EP-079 --out docs/trace/EP-079.md
  python3 tools/docs/trace-epic.py EP-079 --ref origin/main       # storia da leggere (default HEAD)

Solo stdlib e git.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def git(*args: str) -> str:
    r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else ""


def frontmatter(p: Path) -> tuple[dict, str]:
    return frontmatter_testo(p.read_text(encoding="utf-8"))


def frontmatter_testo(t: str) -> tuple[dict, str]:
    m = re.match(r"---\n(.*?)\n---\n?(.*)", t, re.S)
    if not m:
        return {}, t
    fm: dict = {}
    chiave = None
    for riga in m.group(1).splitlines():
        lista = re.match(r"\s+-\s+(.*)", riga)
        if lista and chiave:
            fm.setdefault(chiave, []).append(lista.group(1).strip().strip('"'))
            continue
        kv = re.match(r"([a-z_]+):\s*(.*)", riga)
        if kv:
            chiave, valore = kv.group(1), kv.group(2).strip().strip('"')
            fm[chiave] = valore if valore else []
    return fm, m.group(2)


def sezione(corpo: str, titolo: str) -> str:
    m = re.search(rf"^## {re.escape(titolo)}\s*\n(.*?)(?=^## |\Z)", corpo, re.M | re.S)
    return m.group(1).strip() if m else ""


def esiti(tabella: str) -> dict[str, int]:
    conta: dict[str, int] = {}
    for riga in tabella.splitlines():
        celle = [c.strip() for c in riga.strip().strip("|").split("|")]
        if len(celle) >= 2 and celle[0] and not set(celle[0]) <= {"-"} and celle[0] != "AC":
            esito = re.split(r"[:\s]", celle[1])[0].upper() or "?"
            conta[esito] = conta.get(esito, 0) + 1
    return conta


def traccia(ep: str, ref: str) -> str:
    dirs = sorted((ROOT / "management" / "kanban").glob(f"{ep}-*"))
    if not dirs:
        raise SystemExit(f"epica {ep} non trovata in management/kanban/")
    d = dirs[0]
    ep_fm, ep_corpo = frontmatter(d / f"{ep}.md")
    out = [f"# Trace of {ep} — {ep_fm.get('title', '')}", ""]
    sha = git("rev-parse", "--short", ref).strip()
    out += [f"> Generated by `python3 tools/docs/trace-epic.py {ep}` from the kanban and the git "
            f"history at `{ref}` ({sha}). Do not edit by hand: regenerate. Content quoted from the "
            "kanban is in Italian, the working language of this repository.", ""]

    out += ["## 1. Why: the decision", ""]
    for s in ep_fm.get("source", []) or []:
        out.append(f"- {s}")
    vincoli = ep_fm.get("constraints", []) or []
    if vincoli:
        out += ["", "Constraints declared up front:", ""] + [f"- {v}" for v in vincoli]

    out += ["", "## 2. What: stories and tasks", ""]
    ids_tsk: list[str] = []
    for us_dir in sorted(p for p in d.iterdir() if p.is_dir()):
        us_file = next(us_dir.glob("US-*.md"), None)
        if not us_file:
            continue
        us_fm, us_corpo = frontmatter(us_file)
        out += [f"### {us_fm.get('id')} — {us_fm.get('title', '')}", "",
                f"Status: `{us_fm.get('status')}`. Acceptance criteria, as written in the story:", "",
                sezione(us_corpo, "Criteri di accettazione"), ""]
        out += ["| Task | Title | Status | Started | Closed | Closing evidence |", "|---|---|---|---|---|---|"]
        chiusure = []
        for t in sorted(us_dir.glob("TSK-*.md")):
            fm, corpo = frontmatter(t)
            ids_tsk.append(fm.get("id", t.stem))
            chiusura = sezione(corpo, "Chiusura")
            conta = esiti(chiusura)
            sintesi = ", ".join(f"{n} {k}" for k, n in sorted(conta.items())) or "—"
            out.append(f"| {fm.get('id')} | {fm.get('title', '')} | `{fm.get('status')}` "
                       f"| {fm.get('started_at', '—')} | {fm.get('closed_at', '—')} | {sintesi} |")
            if chiusura:
                chiusure.append((fm.get("id"), chiusura))
        for tid, testo in chiusure:
            out += ["", f"#### {tid} — closure, verbatim", "", testo]
        out.append("")

    out += ["## 3. How: commits and pull request", ""]
    grep = [f"--grep={ep}"] + [f"--grep={i}" for i in ids_tsk]
    righe = git("log", ref, "--no-merges", "--date=short", "--format=%h|%ad|%s", *grep).splitlines()
    out += ["| Commit | Date | Subject |", "|---|---|---|"]
    out += [f"| `{h}` | {data} | {sogg} |" for h, data, sogg in (r.split("|", 2) for r in righe)]
    branch = ep_fm.get("branch")
    if branch:
        merge = git("log", ref, "--merges", "--date=short", "--format=%h|%ad|%s",
                    f"--grep=from [^ ]*/{re.escape(branch)}$").splitlines()
        out.append("")
        if merge:
            h, data, sogg = merge[0].split("|", 2)
            pr = re.search(r"#(\d+)", sogg)
            out.append(f"Merged into `{ref}` on {data} by `{h}`: {sogg}"
                       + (f" ([PR #{pr.group(1)}](https://github.com/soli92/soli-multi-agents-factory/pull/{pr.group(1)}))" if pr else ""))
        else:
            out.append(f"Branch `{branch}`: no merge found in `{ref}`.")

    out += ["", "## 4. Record: wiki/log.md", ""]
    log = (ROOT / "wiki" / "log.md").read_text(encoding="utf-8")
    voci = [v for v in re.split(r"(?=^## \[)", log, flags=re.M) if v.startswith("## [") and ep in v.splitlines()[0]]
    # citate, non incollate: i titoli `## [...]` del log romperebbero la gerarchia della pagina
    for v in voci:
        righe = [re.sub(r"^## (.*)", r"**\1**", r) for r in v.strip().splitlines()]
        out += ["\n".join("> " + r if r else ">" for r in righe), ""]
    if not voci:
        out.append("No entry names this epic in its heading.")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("epica", help="ID dell'epica, es. EP-079")
    ap.add_argument("--ref", default="HEAD", help="storia git da leggere (default HEAD)")
    ap.add_argument("--out", type=Path, help="file di destinazione (default stdout)")
    a = ap.parse_args()
    testo = traccia(a.epica, a.ref)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(testo, encoding="utf-8")
        print(f"scritto {a.out}")
    else:
        sys.stdout.write(testo)
    return 0


if __name__ == "__main__":
    sys.exit(main())
