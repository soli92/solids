"""Fonte unica dei pattern §ai_policy — ADR-074.

Questo modulo e' la **single source of truth** per i pattern di attribution AI e per
gli ID del kanban factory. Nessun altro file li ridefinisce.

Perche' esiste: i commit dei repo cliente con ``suppress_ai_traces: true`` non devono
contenere ne' tracce di attribution AI (``Co-Authored-By: ...``, ``Generated with ...``)
ne' ID interni del kanban factory (TSK-NNN, US-NNN, EP-NNN). Questo modulo espone le
funzioni di rilevamento e rimozione usate dagli strumenti Layer-1 (hook git) e Layer-2
(scan detective). Avere la logica in un posto solo garantisce coerenza tra i due layer.

Nomi di cliente: nessuno. Gli esempi usano ID generici (XX-, XXX-).
"""
from __future__ import annotations

import re
from typing import List, Tuple

# ---------------------------------------------------------------------------
# Attribution AI
# ---------------------------------------------------------------------------

# Substring che identificano una riga di attribution AI.
# Confronto case-insensitive nel chiamante (lowercased in is_ai_attribution).
# Allineate ai pattern degli hook git Layer-1.
AI_SUBSTRINGS: Tuple[str, ...] = (
    "co-authored-by",
    "generated with",
    "generated by",
    "claude",
    "anthropic",
)


def is_ai_attribution(line: str) -> bool:
    """True se la riga contiene almeno una substring di attribution AI.

    Il confronto e' case-insensitive.
    """
    low = line.lower()
    return any(sub in low for sub in AI_SUBSTRINGS)


def strip_ai_attribution(message: str) -> Tuple[str, List[str]]:
    """Rimuove le righe di attribution AI dal messaggio di commit.

    Ritorna ``(messaggio_filtrato, righe_rimosse)``. L'ordine delle righe rimaste
    e' preservato. Se non trova nulla ritorna il messaggio invariato e lista vuota.

    La rimozione e' per **riga intera** (come fa il Layer-1 bash): l'attribution e'
    sempre una riga dedicata (``Co-Authored-By: ...``), non un token inline.
    """
    kept: List[str] = []
    dropped: List[str] = []
    for line in message.splitlines():
        if is_ai_attribution(line):
            dropped.append(line)
        else:
            kept.append(line)
    return "\n".join(kept), dropped


# ---------------------------------------------------------------------------
# ID kanban factory
# ---------------------------------------------------------------------------

# Pattern degli ID interni del kanban.
#
# La flotta di factory usa DUE convenzioni:
#   - senza prefisso namespace:  TSK-690, US-296, EP-068
#     (factory base, quella che contiene questo file)
#   - con prefisso namespace:    XX-TSK-268, XXX-US-206, XXXX-EP-019
#     (factory derivate multi-namespace con 2-4 lettere maiuscole di prefisso)
#
# Il prefisso e' reso OPZIONALE con ``(?:[A-Z]{2,4}-)?`` cosi' il regex funziona
# in entrambi i contesti senza rompere ne' l'uno ne' l'altro.
#
# Case-sensitive per costruzione: la parola «task», un numero nudo (es. 29174),
# «re 249» e qualsiasi stringa lowercase NON matchano.
FACTORY_ID_RE = re.compile(r"\b(?:[A-Z]{2,4}-)?(?:TSK|US|EP)-\d+\b")


def find_factory_ids(text: str) -> List[str]:
    """Ritorna la lista di ID kanban factory presenti nel testo.

    Esempi che matchano: ``TSK-690``, ``US-296``, ``EP-068``, ``XX-TSK-268``.
    Esempi che NON matchano: ``task``, ``29174``, ``re 249``.
    """
    return FACTORY_ID_RE.findall(text)


def strip_factory_ids(message: str) -> Tuple[str, List[str]]:
    """Rimuove gli ID kanban factory dal messaggio di commit.

    A differenza di :func:`strip_ai_attribution` (che droppa **righe intere**),
    l'ID factory e' tipicamente incastonato nel subject o nel corpo, quindi va
    rimosso solo il **token** con i delimitatori adiacenti, preservando il resto.

    Forme gestite (in ordine di precedenza):
      1. Delimitato da parentesi/parentesi quadre con spazio a monte:
         ``fix: thing (TSK-690)``  →  ``fix: thing``
         ``fix: thing [XX-TSK-268]``  →  ``fix: thing``
      2. Prefisso a inizio riga seguito da ``:`` o ``-``:
         ``TSK-690: subject``  →  ``subject``
         ``XX-TSK-268 - subject``  →  ``subject``
      3. Token nudo residuo (fallback):
         ``rollback TSK-690 hotfix``  →  ``rollback  hotfix``  (spazio doppio poi normalizzato)

    Ritorna ``(messaggio_pulito, id_rimossi)``. Se non trova nulla ritorna il messaggio
    invariato e lista vuota.
    """
    removed = find_factory_ids(message)
    if not removed:
        return message, []

    id_pat = FACTORY_ID_RE.pattern
    cleaned = message

    # 1. Forme delimitate: ' [TSK-690]' / ' (XX-TSK-268)' (con eventuale spazio a monte)
    cleaned = re.sub(r"\s*[\[(]\s*" + id_pat + r"\s*[\])]", "", cleaned)
    # 2. Forma prefisso a inizio riga: 'TSK-690: ' / 'XX-TSK-268 - '
    cleaned = re.sub(r"(?m)^" + id_pat + r"\s*[:\-–]\s*", "", cleaned)
    # 3. Token residui nudi
    cleaned = re.sub(id_pat, "", cleaned)
    # 4. Normalizza spazi multipli lasciati dai tagli
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    cleaned = "\n".join(line.rstrip() for line in cleaned.splitlines())

    return cleaned.strip("\n"), removed
