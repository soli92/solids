#!/usr/bin/env python3
"""
install_submodule_hooks.py -- installa i hook §ai_policy nei submodule gestiti.

Porta cross-platform generalizzata (US-311 EP-069): nessuna costante verticale.
I submodule target sono quelli dichiarati in factory.config.yaml come
code_paths[] con vcs.mode: submodule.

GATING ai_policy:
  Gli hook §ai_policy (pre-commit + commit-msg) vengono installati SOLO SE
  ai_attribution_policy.suppress_ai_traces: true in factory.config.yaml.
  Se il flag e' assente o false, lo strumento avvisa e non installa nulla
  (nessun errore: la policy non si applica, non e' un guasto).

USO:
  python3 tools/vcs/install_submodule_hooks.py [--dry-run] [--target <nome>] [--force]

  --dry-run   mostra cosa verrebbe installato, senza modificare nulla.
  --target    solo il submodule indicato (default: tutti dichiarati in config).
  --force     sovrascrive hook esistenti senza prompt.

Idempotente via sha256 (stdlib). stdlib-only, cross-platform.

Riferimenti: tools/vcs/ai_policy.py (fonte unica pattern §ai_policy)
             tools/vcs/sm_doctor.py, tools/vcs/README-submodule.md
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

# Rende importabile smlib da qualsiasi CWD
sys.path.insert(0, str(Path(__file__).resolve().parent))

from smlib import (
    color,
    factory_name,
    factory_root,
    list_submodule_paths,
    resolve_submodule,
    suppress_ai_traces,
)
from smlib.factory_config import list_submodule_code_paths

# ---------------------------------------------------------------------------
# Contenuto hook -- bash (Git for Windows li invoca via shebang).
# Pattern allineati ad AI_SUBSTRINGS di tools/vcs/ai_policy.py.
# NON modificare senza aggiornare anche ai_policy.py.
# ---------------------------------------------------------------------------
PRE_COMMIT_HOOK = r'''#!/usr/bin/env bash
# pre-commit hook -- §ai_policy enforcement (PATTERN §23.9)
# Blocca commit il cui diff staged contiene attribution AI.
# NON bypassabile senza --no-verify (vietato da §ai_policy).
set -euo pipefail

RED='\033[0;31m'; YELLOW='\033[1;33m'; NC='\033[0m'

AI_PATTERNS='Co-Authored-By:\|Co-authored-by:\|Generated with\|Generated by\|generated with\|generated by\|claude\|anthropic'

STAGED_DIFF=$(git diff --cached --unified=0 2>/dev/null || true)
if [[ -z "$STAGED_DIFF" ]]; then exit 0; fi

DIFF_MATCH=$(echo "$STAGED_DIFF" | grep -n '^+' | grep -iv '^+++' \
  | grep -i "$AI_PATTERNS" | head -5 || true)

if [[ -z "$DIFF_MATCH" ]]; then exit 0; fi

echo ""
echo -e "${RED}[§ai_policy] BLOCCO: attribution AI rilevata nel diff staged.${NC}"
echo -e "${YELLOW}PATTERN §23.9 -- suppress_ai_traces attivo su questo repo.${NC}"
echo ""
echo -e "${RED}Pattern trovato:${NC}"
echo "$DIFF_MATCH" | while IFS= read -r line; do echo "  $line"; done
echo ""
echo "Azioni: rimuovi il pattern, ri-stage, ri-esegui il commit."
echo "  Per strip automatico: python3 tools/vcs/sm_commit.py \"<msg pulito>\""
echo ""
exit 1
'''

COMMIT_MSG_HOOK = r'''#!/usr/bin/env bash
# commit-msg hook -- §ai_policy enforcement (PATTERN §23.9)
# Blocca attribution AI e ID kanban factory nel messaggio.
# NON bypassabile senza --no-verify (vietato da §ai_policy).
set -euo pipefail

RED='\033[0;31m'; YELLOW='\033[1;33m'; NC='\033[0m'

MSG_FILE="$1"
if [[ ! -f "$MSG_FILE" ]]; then exit 0; fi

AI_PATTERNS='Co-Authored-By:\|Co-authored-by:\|Generated with\|Generated by\|generated with\|generated by\|claude\|anthropic'
FACTORY_ID_PATTERN='[A-Z]{2,4}-(TSK|US|EP)-[0-9]+'

MSG_MATCH=$(grep -i "$AI_PATTERNS" "$MSG_FILE" | head -3 || true)
if [[ -n "$MSG_MATCH" ]]; then
  echo ""
  echo -e "${RED}[§ai_policy] BLOCCO: attribution AI nel messaggio di commit.${NC}"
  echo -e "${YELLOW}PATTERN §23.9 -- suppress_ai_traces attivo.${NC}"
  echo ""
  echo "$MSG_MATCH" | while IFS= read -r line; do echo "  $line"; done
  echo ""
  echo "Modifica il messaggio e ri-esegui. Strip automatico:"
  echo "  python3 tools/vcs/sm_commit.py \"<msg pulito>\""
  echo ""
  exit 1
fi

FACTORY_ID_MATCH=$(grep -oE "$FACTORY_ID_PATTERN" "$MSG_FILE" | head -3 || true)
if [[ -n "$FACTORY_ID_MATCH" ]]; then
  echo ""
  echo -e "${RED}[§ai_policy] BLOCCO: ID kanban factory nel messaggio di commit.${NC}"
  echo -e "${YELLOW}Gli ID interni non vanno nella history del repo cliente.${NC}"
  echo ""
  echo "$FACTORY_ID_MATCH" | while IFS= read -r line; do echo "  $line"; done
  echo ""
  echo "Rimuovi il tag e ri-esegui. Il legame commit<->task va nel kanban factory."
  echo ""
  exit 1
fi

exit 0
'''

HOOKS = {
    "pre-commit": PRE_COMMIT_HOOK,
    "commit-msg": COMMIT_MSG_HOOK,
}


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _prompt(msg: str) -> str:
    """Legge da /dev/tty se disponibile (macOS/Linux/Git Bash), altrimenti stdin."""
    try:
        with open("/dev/tty", "r") as tty:
            sys.stdout.write(msg)
            sys.stdout.flush()
            return tty.readline().strip()
    except OSError:
        return input(msg).strip()


def _hooks_path_override(sm_path: Path) -> str:
    """Ritorna il valore di core.hooksPath se il repo lo ridirige (es. husky), '' altrimenti.

    Quando core.hooksPath e' impostato, git IGNORA .git/hooks: gli hook §ai_policy
    installati qui NON verrebbero mai eseguiti. Rilevarlo evita il fallimento silenzioso.
    """
    try:
        out = subprocess.run(
            ["git", "-C", str(sm_path), "config", "--get", "core.hooksPath"],
            capture_output=True, text=True, timeout=15,
        )
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:
        return ""


def _resolve_hooks_dir(sm_path: Path) -> Path:
    """Directory hooks reale del submodule (gestisce il file .git -> gitdir:)."""
    git_marker = sm_path / ".git"
    if git_marker.is_file():
        raw = git_marker.read_text(encoding="utf-8").strip()
        gitdir = raw.split("gitdir:", 1)[1].strip() if "gitdir:" in raw else raw
        gitdir_path = Path(gitdir)
        if not gitdir_path.is_absolute():
            gitdir_path = (sm_path / gitdir_path).resolve()
        return gitdir_path / "hooks"
    return sm_path / ".git" / "hooks"


class Counters:
    def __init__(self) -> None:
        self.installed = 0
        self.skipped = 0
        self.conflicts = 0


def _install_hook(name: str, content: str, hooks_dir: Path,
                  dry_run: bool, force: bool, counters: Counters) -> None:
    hook_path = hooks_dir / name
    expected = _sha256(content.encode("utf-8"))

    if hook_path.exists():
        existing = _sha256(hook_path.read_bytes())
        if existing == expected:
            print("    " + color.green(f"OK -- {name} gia' aggiornato (checksum identico)."))
            counters.skipped += 1
            return
        print("    " + color.yellow(f"ATTENZIONE -- esiste un {name} diverso: {hook_path}"))
        if dry_run:
            print("    " + color.yellow("[dry-run] Sovrascrittura richiesta -- esegui senza --dry-run."))
            counters.conflicts += 1
            return
        if force:
            print("    " + color.yellow(f"--force: sovrascrittura automatica di {name}."))
        else:
            confirm = _prompt(f"    Sovrascrivere il hook {name} esistente? [y/N] ")
            if confirm not in ("y", "Y"):
                print("    " + color.yellow(f"SKIP -- {name} non sovrascritto."))
                counters.skipped += 1
                return

    if dry_run:
        print("    " + color.cyan(f"[dry-run] Installerebbe {name} in: {hook_path}"))
        print("    Contenuto (prime 5 righe):")
        for line in content.splitlines()[:5]:
            print(f"      {line}")
        print("      ...")
        return

    hook_path.write_text(content, encoding="utf-8")
    hook_path.chmod(0o755)
    print("    " + color.green(f"Installato: {hook_path}"))
    counters.installed += 1


def _target_submodules(root: Path, target: str):
    """Submodule target da operare. Usa i path da .gitmodules filtrati per config."""
    config_paths = {
        entry.get("path", "").strip("/")
        for entry in list_submodule_code_paths(root)
        if entry.get("path")
    }
    # Nomi (basename) dei submodule configurati
    config_names = {
        Path(p).name for p in config_paths
    } | {
        entry.get("name", "")
        for entry in list_submodule_code_paths(root)
    }

    all_paths = list_submodule_paths(root)

    if not target:
        # Tutti i submodule presenti in .gitmodules che sono anche in config
        if not config_paths and not config_names:
            return []
        return [p for p in all_paths
                if p in config_paths or Path(p).name in config_names]

    resolved = resolve_submodule(root, target)
    if resolved and (
        resolved in config_paths
        or Path(resolved).name in config_names
        or not list_submodule_code_paths(root)  # se config vuoto, accetta tutti
    ):
        return [resolved]
    return []


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Installa i hook §ai_policy nei submodule dichiarati in config.",
    )
    parser.add_argument("--dry-run", action="store_true",
                        help="Mostra cosa verrebbe installato.")
    parser.add_argument("--target", default="",
                        help="Solo il submodule indicato (default: tutti in config).")
    parser.add_argument("--force", action="store_true",
                        help="Sovrascrive hook esistenti senza prompt.")
    args = parser.parse_args(argv)

    root = factory_root()

    # Check suppress_ai_traces
    if not suppress_ai_traces(root):
        print(color.cyan("Info: ai_attribution_policy.suppress_ai_traces non e' true in factory.config.yaml."))
        print(color.cyan("      Gli hook §ai_policy non sono necessari (la policy non si applica)."))
        print(color.cyan("      Nessuna installazione eseguita."))
        print()
        print("Per abilitare: imposta ai_attribution_policy.suppress_ai_traces: true")
        print("               e ri-esegui questo installer.")
        return 0

    submodules = _target_submodules(root, args.target)

    if not submodules:
        suffix = f" per target '{args.target}'" if args.target else ""
        print(color.yellow(
            f"Nessun submodule dichiarato in factory.config.yaml{suffix} "
            f"(vcs.mode: submodule)."
        ))
        print(color.cyan(
            "Se il submodule esiste in .gitmodules ma non in factory.config.yaml, "
            "aggiungilo come entry code_paths[] con vcs.mode: submodule."
        ))
        return 0

    counters = Counters()
    for sm_relpath in submodules:
        sm_path = root / sm_relpath
        print(color.cyan(f"Submodule: {sm_relpath}"))

        if not (sm_path / ".git").exists():
            print("  " + color.yellow(
                f"SKIP -- submodule non inizializzato "
                f"(esegui: git submodule update --init {sm_relpath})"))
            counters.skipped += 2
            continue

        override = _hooks_path_override(sm_path)
        if override:
            print("  " + color.red(
                f"ATTENZIONE -- core.hooksPath = '{override}' (es. husky): "
                f"git NON esegue .git/hooks."))
            print("  " + color.yellow(
                "  Gli hook §ai_policy installati qui sarebbero INERTI. "
                "Vedi tools/vcs/README-submodule.md per il workaround."))
            counters.skipped += 2
            continue

        hooks_dir = _resolve_hooks_dir(sm_path)
        if not hooks_dir.is_dir():
            if args.dry_run:
                print("  " + color.yellow(f"[dry-run] Creerebbe directory: {hooks_dir}"))
            else:
                hooks_dir.mkdir(parents=True, exist_ok=True)

        print("  " + color.cyan("pre-commit") + " (diff staged):")
        _install_hook("pre-commit", HOOKS["pre-commit"], hooks_dir,
                      args.dry_run, args.force, counters)

        print("  " + color.cyan("commit-msg") + " (messaggio di commit):")
        _install_hook("commit-msg", HOOKS["commit-msg"], hooks_dir,
                      args.dry_run, args.force, counters)

    print()
    if args.dry_run:
        print(color.cyan(
            f"[dry-run] Riepilogo: {counters.installed} da installare, "
            f"{counters.skipped} skip, {counters.conflicts} conflitti."))
        print(color.yellow("Esegui senza --dry-run per procedere."))
    else:
        print(color.green(
            f"Riepilogo: {counters.installed} hook installati, {counters.skipped} skip."))
        if counters.installed > 0:
            print()
            print(color.yellow("NOTA: i hook vanno re-installati dopo ogni git submodule update --init."))
            print(color.yellow("      Usa --force per sovrascrivere senza prompt."))
    return 0


# Ri-esporta per sm_doctor.py (single source of truth su HOOKS e helper)
def get_hooks() -> dict:
    return HOOKS


def sha256(data: bytes) -> str:
    return _sha256(data)


def resolve_hooks_dir(sm_path: Path) -> Path:
    return _resolve_hooks_dir(sm_path)


if __name__ == "__main__":
    sys.exit(main())
