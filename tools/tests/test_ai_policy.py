class TestStripAiAttribution(unittest.TestCase):
    """strip_ai_attribution droppa righe intere che matchano."""

    def test_removes_coauthored_line(self):
        msg = "fix: thing\n\nCo-Authored-By: Claude Sonnet 4.6 <noreply@anthropic.com>"
        cleaned, dropped = strip_ai_attribution(msg)
        self.assertNotIn("Co-Authored-By", cleaned)
        self.assertEqual(len(dropped), 1)
        self.assertIn("Co-Authored-By", dropped[0])

    def test_keeps_non_attribution_lines(self):
        msg = "feat: add feature\n\nSome body text\n\nCo-Authored-By: AI"
        cleaned, dropped = strip_ai_attribution(msg)
        self.assertIn("feat: add feature", cleaned)
        self.assertIn("Some body text", cleaned)

    def test_no_attribution(self):
        msg = "fix: nothing to strip here"
        cleaned, dropped = strip_ai_attribution(msg)
        self.assertEqual(cleaned, msg)
        self.assertEqual(dropped, [])

    def test_empty_message(self):
        cleaned, dropped = strip_ai_attribution("")
        self.assertEqual(cleaned, "")
        self.assertEqual(dropped, [])

    def test_multiple_attribution_lines(self):
        msg = "feat: x\nCo-Authored-By: AI\nGenerated by: tool\nstay"
        cleaned, dropped = strip_ai_attribution(msg)
        self.assertEqual(len(dropped), 2)
        self.assertIn("stay", cleaned)
        self.assertNotIn("Co-Authored-By", cleaned)
        self.assertNotIn("Generated by", cleaned)


class TestFactoryIdRe(unittest.TestCase):
    """FACTORY_ID_RE deve matchare entrambe le convenzioni e rifiutare i falsi positivi."""

    # --- forme valide ---

    def test_no_prefix_tsk(self):
        """TSK-690 (questa factory, senza namespace)."""
        self.assertRegex("TSK-690", FACTORY_ID_RE)

    def test_no_prefix_us(self):
        """US-296 (questa factory)."""
        self.assertRegex("US-296", FACTORY_ID_RE)

    def test_no_prefix_ep(self):
        """EP-068 (questa factory)."""
        self.assertRegex("EP-068", FACTORY_ID_RE)

    def test_two_char_prefix_tsk(self):
        """XX-TSK-268 (factory derivata, prefisso 2 lettere)."""
        self.assertRegex("XX-TSK-268", FACTORY_ID_RE)

    def test_three_char_prefix_us(self):
        """XXX-US-206 (factory derivata, prefisso 3 lettere)."""
        self.assertRegex("XXX-US-206", FACTORY_ID_RE)

    def test_four_char_prefix_ep(self):
        """XXXX-EP-019 (factory derivata, prefisso 4 lettere)."""
        self.assertRegex("XXXX-EP-019", FACTORY_ID_RE)

    def test_inline_in_text(self):
        """ID trovato all'interno di una frase."""
        ids = find_factory_ids("fix: resolve issue from TSK-42 and EP-007")
        self.assertIn("TSK-42", ids)
        self.assertIn("EP-007", ids)

    # --- falsi positivi OBBLIGATORI (AC2) ---

    def test_fp_word_task(self):
        """La parola «task» non deve matchare (lowercase)."""
        ids = find_factory_ids("task: update the task list")
        self.assertEqual(ids, [], f"Falso positivo su 'task': {ids}")

    def test_fp_bare_number(self):
        """Un numero nudo (29174) non deve matchare."""
        ids = find_factory_ids("ADO work item 29174 closed")
        self.assertEqual(ids, [], f"Falso positivo su numero nudo: {ids}")

    def test_fp_re_249(self):
        """«re 249» non deve matchare."""
        ids = find_factory_ids("see re 249 for details")
        self.assertEqual(ids, [], f"Falso positivo su 're 249': {ids}")

    def test_fp_lowercase_hyphenated(self):
        """Una parola minuscola con trattini non deve matchare."""
        ids = find_factory_ids("tsk-123 fix-it us-east-1")
        self.assertEqual(ids, [], f"Falso positivo su lowercase: {ids}")

    def test_fp_mixed_case_prefix_lower(self):
        """'Ps-TSK-123' contiene 'TSK-123' valido (no-prefix form): match atteso.

        Il test verifica che il regex NON confonda il prefisso misto come ID autonomo,
        ma lo 'TSK-123' interno e' un ID factory legittimo e viene correttamente trovato.
        Questo non e' un falso positivo: e' comportamento corretto.
        """
        ids = find_factory_ids("Ps-TSK-123")
        # TSK-123 senza prefisso e' un ID valido di questa factory
        self.assertIn("TSK-123", ids)

    def test_fp_us_east_region(self):
        """AWS region 'US-EAST-1' non deve matchare (EAST non e' TSK|US|EP)."""
        ids = find_factory_ids("deploy on US-EAST-1")
        self.assertEqual(ids, [], f"Falso positivo su AWS region: {ids}")


class TestFindFactoryIds(unittest.TestCase):
    """find_factory_ids ritorna tutti gli ID trovati nel testo."""

    def test_empty_text(self):
        self.assertEqual(find_factory_ids(""), [])

    def test_multiple_ids(self):
        ids = find_factory_ids("relates to TSK-1 and US-2 and EP-3")
        self.assertIn("TSK-1", ids)
        self.assertIn("US-2", ids)
        self.assertIn("EP-3", ids)

    def test_duplicate_ids(self):
        ids = find_factory_ids("TSK-5 fixed, see TSK-5")
        self.assertEqual(ids.count("TSK-5"), 2)

    def test_returns_list(self):
        result = find_factory_ids("EP-001")
        self.assertIsInstance(result, list)


class TestStripFactoryIds(unittest.TestCase):
    """strip_factory_ids rimuove il token ID con i delimitatori adiacenti."""

    def test_no_ids(self):
        msg = "fix: nothing to strip"
        cleaned, removed = strip_factory_ids(msg)
        self.assertEqual(cleaned, msg)
        self.assertEqual(removed, [])

    def test_form_parentheses(self):
        """Forma delimitata da parentesi tonde: 'fix: thing (TSK-690)'."""
        msg = "fix: thing (TSK-690)"
        cleaned, removed = strip_factory_ids(msg)
        self.assertNotIn("TSK-690", cleaned)
        self.assertIn("TSK-690", removed)
        self.assertIn("fix: thing", cleaned)

    def test_form_square_brackets(self):
        """Forma delimitata da parentesi quadre: 'feat: x [XX-TSK-268]'."""
        msg = "feat: x [XX-TSK-268]"
        cleaned, removed = strip_factory_ids(msg)
        self.assertNotIn("XX-TSK-268", cleaned)
        self.assertIn("XX-TSK-268", removed)
        self.assertIn("feat: x", cleaned)

    def test_form_prefix_colon(self):
        """Forma prefisso con ':': 'TSK-690: subject line'."""
        msg = "TSK-690: subject line"
        cleaned, removed = strip_factory_ids(msg)
        self.assertNotIn("TSK-690", cleaned)
        self.assertIn("TSK-690", removed)
        self.assertIn("subject line", cleaned)

    def test_form_prefix_dash(self):
        """Forma prefisso con ' - ': 'XX-TSK-268 - subject'."""
        msg = "XX-TSK-268 - subject"
        cleaned, removed = strip_factory_ids(msg)
        self.assertNotIn("XX-TSK-268", cleaned)
        self.assertIn("XX-TSK-268", removed)
        self.assertIn("subject", cleaned)

    def test_form_bare_token(self):
        """Token nudo nel body: 'rollback TSK-42 hotfix'."""
        msg = "rollback TSK-42 hotfix"
        cleaned, removed = strip_factory_ids(msg)
        self.assertNotIn("TSK-42", cleaned)
        self.assertIn("TSK-42", removed)
        # dopo normalizzazione spazi non ci sono doppi spazi
        self.assertNotIn("  ", cleaned)

    def test_returns_tuple(self):
        result = strip_factory_ids("EP-001: subject")
        self.assertIsInstance(result, tuple)
        self.assertEqual(len(result), 2)

    def test_multiple_ids_removed(self):
        msg = "fix (TSK-1): relates to EP-2"
        cleaned, removed = strip_factory_ids(msg)
        self.assertNotIn("TSK-1", cleaned)
        self.assertNotIn("EP-2", cleaned)
        self.assertEqual(len(removed), 2)


